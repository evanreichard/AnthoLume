import { ko } from './ko';
import { test, expect, register } from './fixtures';
import { pendingIds, serverEffects, storedRows } from './storage';

test('real KO conflict invalidates a stale local choice, accepts explicit backward position, and preserves independent activity', async ({ page, context, server }) => {
  const user = `ko-${Date.now()}`;
  await register(page, server.origin, user);
  await page.getByRole('heading', { name: 'Public book 01', exact: true }).click();
  const detail = page.url();
  await page.getByRole('link', { name: /^(Read|Resume)$/ }).click();
  await expect(page.locator('footer')).toContainText('1 /');
  await context.setOffline(true);
  await page.waitForTimeout(15_000);
  await page.keyboard.press('c');
  await page.getByRole('button', { name: 'Next page', exact: true }).click();
  await expect(page.locator('footer')).toContainText('2 /');
  await expect.poll(async () => (await storedRows(page, 'events')).length).toBe(2);
  const checkpoint = (await storedRows(page, 'books'))[0].checkpoint!;
  await page.keyboard.press('c');
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await ko(server.origin, user, .8);
  await context.setOffline(false);
  await page.goto(`${server.origin}/settings?sync=open`);
  await expect(page.getByRole('button', { name: 'Refresh shared position', exact: true })).toBeVisible();
  await expect.poll(() => serverEffects(server.data, user).activity).toBe(1);
  await page.getByRole('button', { name: 'Refresh shared position', exact: true }).click();
  await expect(page.getByText('Shared position: 80%', { exact: false })).toBeVisible();
  await ko(server.origin, user, .9);
  await page.getByRole('button', { name: 'Use this device’s position (may move backward)', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Refresh shared position', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Refresh shared position', exact: true }).click();
  await expect(page.getByText('Shared position: 90%', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Use this device’s position (may move backward)', exact: true }).click();
  await expect.poll(() => pendingIds(page)).toEqual([]);
  let shared = await ko(server.origin, user);
  expect(shared.progress).toBe(checkpoint.position);
  expect(shared.percentage).toBe(checkpoint.fraction);
  expect(serverEffects(server.data, user).activity).toBe(1);

  await page.goto(detail);
  await page.getByRole('link', { name: /^(Read|Resume)$/ }).click();
  await expect(page.locator('iframe').first()).toBeVisible();
  await expect(page.locator('footer')).toContainText('/');
  await ko(server.origin, user, .95);
  await page.keyboard.press('c');
  await page.getByRole('button', { name: 'Next page', exact: true }).click();
  await expect.poll(async () => (await pendingIds(page)).length).toBe(1);
  await page.keyboard.press('c');
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await page.goto(`${server.origin}/settings?sync=open`);
  await expect(page.getByRole('button', { name: 'Refresh shared position', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Refresh shared position', exact: true }).click();
  await expect(page.getByText('Shared position: 95%', { exact: false })).toBeVisible();
  const before = serverEffects(server.data, user);
  await page.getByRole('button', { name: 'Use shared position', exact: true }).click();
  await expect.poll(() => pendingIds(page)).toEqual([]);
  expect((await storedRows(page, 'books'))[0].checkpoint?.fraction).toBe(.95);
  expect(serverEffects(server.data, user)).toEqual(before);
  shared = await ko(server.origin, user);
  expect(shared.percentage).toBe(.95);
});
